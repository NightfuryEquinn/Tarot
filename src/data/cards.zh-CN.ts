function entries(prefix: string, data: Entry[], offset = 1): [string, CardCopy][] {
  return data.map(([name, uk, text, advice, rk, reversedText, reversedAdvice], i) => [
    `${prefix}-${String(i + offset).padStart(2, '0')}`,
    { name, upright: { keywords: uk.split('|'), text, advice }, reversed: { keywords: rk.split('|'), text: reversedText, advice: reversedAdvice } },
  ]);
}

